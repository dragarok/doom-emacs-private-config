#!/usr/bin/env python3
"""Iosevka outlines for the week calendar (org-timegrid) on the phone.

Android's SVG renderer finds no fonts, so org-timegrid draws its text as
shapes, from a bundled table of Noto Sans outlines.  This writes the same
table from Iosevka -- the phone Emacs's own font -- so the calendar reads
like the rest of Emacs.  config.el swaps it in.

    uv run --with fonttools python3 etc/make-timegrid-font.py

Reads the Iosevka Nerd Font Mono files in ~/Library/Fonts; writes
lisp/timegrid-iosevka-font.el.  Iosevka is OFL-1.1.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

FONTS = Path.home() / "Library/Fonts"
# org-timegrid draws weight 400, and 500 for titles.
WEIGHTS = {"regular": "IosevkaNerdFontMono-Regular.ttf",
           "bold": "IosevkaNerdFontMono-Medium.ttf"}
# What org-timegrid's own table has: ASCII, dashes, quotes, bullet, ellipsis.
CODEPOINTS = list(range(32, 127)) + [0x2013, 0x2014, 0x2018, 0x2019,
                                     0x201C, 0x201D, 0x2022, 0x2026]
OUT = Path(__file__).resolve().parent.parent / "lisp/timegrid-iosevka-font.el"


def num(x):
    """X with no trailing zeros."""
    s = f"{x:.1f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def table(path):
    font = TTFont(path)
    scale = 1000 / font["head"].unitsPerEm
    cmap, glyphs, hmtx = font.getBestCmap(), font.getGlyphSet(), font["hmtx"]
    rows = []
    for cp in CODEPOINTS:
        name = cmap.get(cp)
        if name is None:
            continue
        pen = SVGPathPen(glyphs, ntos=lambda v: num(v * scale))
        glyphs[name].draw(pen)
        rows.append(f'    ({cp} {round(hmtx[name][0] * scale)} "{pen.getCommands()}")')
    return "\n".join(rows)


def main():
    parts = [";;; timegrid-iosevka-font.el --- Iosevka outlines for org-timegrid on Android -*- lexical-binding: t; -*-",
             "",
             ";; Generated by etc/make-timegrid-font.py from Iosevka Nerd Font Mono",
             ";; (Regular, and Medium for titles).  Do not edit by hand.  Iosevka is",
             ";; Copyright Renzhi Li (Belleve Invis), under the SIL Open Font License 1.1.",
             "",
             ";;; Code:",
             ""]
    for weight, file in WEIGHTS.items():
        parts += [f"(defconst timegrid-iosevka-font-{weight}",
                  "  '(", table(FONTS / file), "    ))", ""]
    parts += ["(provide 'timegrid-iosevka-font)",
              ";;; timegrid-iosevka-font.el ends here", ""]
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
